create extension if not exists pgcrypto;

create table public.curriculum_stages (
  id uuid primary key default gen_random_uuid(),
  curriculum_version text not null,
  position smallint not null check (position > 0),
  slug text not null check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (length(trim(title)) > 0),
  summary_md text not null check (length(trim(summary_md)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (curriculum_version, position),
  unique (curriculum_version, slug),
  unique (id, curriculum_version)
);

create table public.assignments (
  id uuid primary key default gen_random_uuid(),
  stage_id uuid not null,
  curriculum_version text not null,
  position smallint not null check (position > 0),
  slug text not null check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (length(trim(title)) > 0),
  body_md text not null check (length(trim(body_md)) > 0),
  proof_prompt_md text not null check (length(trim(proof_prompt_md)) > 0),
  requires_review boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (curriculum_version, position),
  unique (curriculum_version, slug),
  unique (id, curriculum_version),
  foreign key (stage_id, curriculum_version)
    references public.curriculum_stages(id, curriculum_version)
    on delete restrict
);

create table public.acceptance_criteria (
  id uuid primary key default gen_random_uuid(),
  assignment_id uuid not null references public.assignments(id) on delete cascade,
  position smallint not null check (position > 0),
  criterion text not null check (length(trim(criterion)) > 0),
  created_at timestamptz not null default now(),
  unique (assignment_id, position)
);

create index assignments_stage_id_idx on public.assignments(stage_id);
create index acceptance_criteria_assignment_id_idx on public.acceptance_criteria(assignment_id);

alter table public.curriculum_stages enable row level security;
alter table public.assignments enable row level security;
alter table public.acceptance_criteria enable row level security;

create policy "authenticated users read curriculum stages"
on public.curriculum_stages for select to authenticated using (true);

create policy "authenticated users read assignments"
on public.assignments for select to authenticated using (true);

create policy "authenticated users read acceptance criteria"
on public.acceptance_criteria for select to authenticated using (true);

revoke insert, update, delete on public.curriculum_stages from anon, authenticated;
revoke insert, update, delete on public.assignments from anon, authenticated;
revoke insert, update, delete on public.acceptance_criteria from anon, authenticated;
grant select on public.curriculum_stages, public.assignments, public.acceptance_criteria to authenticated;

